'use strict';
const assert=require('node:assert/strict'),E=require('./engine');
const decide=(s,id,roll=12)=>E.choose(s,id,'gauthier',roll);
const choice=(s,id)=>E.getScene(s).choices.find(c=>c.id===id&&c.condition!==false);
const initial=E.createGame();
assert.equal(E.questJournal(initial).quests.length,6);
assert.equal(E.questJournal(initial).main,'act1');
assert(E.questJournal(initial).quests.every(q=>q.status==='locked'));
let scout=decide(initial,'belle_scout');
scout=decide(scout,'belle_accept');
assert(choice(scout,'quest_plates'));
assert(!choice(scout,'quest_nora'));
scout=decide(scout,'quest_plates');
assert.equal(scout.scene,'side_plates');
scout=decide(scout,'plates_investigate');
assert.equal(scout.scene,'belle_prep');
assert(scout.sideQuests.plates.completed);
assert(scout.flags.sideEscapeRoute);
assert(!choice(scout,'quest_plates'),'une quête annexe terminée ne se rejoue pas');

let nora=decide(initial,'belle_go');
nora=decide(nora,'belle_question');
assert(choice(nora,'quest_nora'),'questionner Lucien peut débloquer Nora');
nora=decide(nora,'quest_nora');
nora=decide(nora,'nora_trust');
assert(nora.flags.noraAlly&&nora.sideQuests.nora.completed);
nora=decide(nora,'belle_bar');
nora=decide(nora,'belle_drink');
assert(choice(nora,'quest_loge'),'une entrée renseignée déverrouille la loge');
nora=decide(nora,'quest_loge');
nora=decide(nora,'loge_read');
assert.equal(choice(nora,'belle_stairvip').dc,7);
nora=decide(nora,'belle_stairside');
nora=decide(nora,'belle_entire');
nora=decide(nora,'belle_parley');
nora=decide(nora,'belle_driving');
assert(nora.completed.belladone&&nora.ended);
nora=E.continueCampaign(nora);
assert.equal(E.questJournal(nora).main,'act2');
assert(choice(nora,'hub_neree'));
assert(choice(nora,'quest_nora_after'));
assert(choice(nora,'quest_mara_favor'));
assert(!choice(nora,'hub_gala'),'le gala final ne se débloque pas avant la deuxième partie');

nora=decide(nora,'quest_nora_after');
nora=decide(nora,'nora_find');
assert(nora.flags.leadPort);
nora=decide(nora,'nora_return');
assert(nora.sideQuests.nora_after.completed);
assert(!choice(nora,'quest_nora_after'));
nora=decide(nora,'quest_mara_favor');
nora=decide(nora,'mara_erase');
nora=decide(nora,'mara_return');
assert(nora.sideQuests.mara_favor.completed&&nora.flags.sideCendreProof);
assert(choice(nora,'hub_convoy'),'les preuves de Mara ouvrent le convoi');
assert(E.publicState(nora).sideQuests.nora_after);
assert.equal(E.questJournal(nora).quests.find(q=>q.id==='mara_favor').status,'done');

let cendre=decide(initial,'belle_go');
cendre=decide(cendre,'belle_accept');
cendre=decide(cendre,'belle_terrace');
cendre=decide(cendre,'belle_follow');
assert(choice(cendre,'quest_cendre'));
cendre=decide(cendre,'quest_cendre');
cendre=decide(cendre,'cendre_delay');
assert(cendre.sideQuests.cendre.completed);
cendre=decide(cendre,'belle_stairvip');
assert.equal(choice(cendre,'belle_entire').dc,11,'retarder Cendre rend le dossier complet un peu plus accessible');
const legacy=E.createGame();delete legacy.sideQuests;
assert.equal(E.questJournal(legacy).quests[0].status,'locked','compatibilité anciennes sauvegardes');
assert(!E.getScene(initial).paragraphs.join(' ').includes('montre'),'aucune montre écrite au prologue');
console.log('Scénario V8 OK : 6 quêtes cachées, déclencheurs, conséquences, retour au fil principal, 2 actes, sauvegarde.');
