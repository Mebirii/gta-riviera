'use strict';
const assert=require('node:assert/strict');
const E=require('./engine'),W=require('./world');
assert.equal(W.DISTRICTS.length,5);
const original=E.createGame();
assert.equal(original.scene,'belle_open');
assert.equal(original.city.district,'belle-rive');
assert.throws(()=>E.worldAction(original,'buy','lockpick'),/quartier/);
assert.throws(()=>E.worldAction(original,'travel','unknown'),/inconnu/);
const port=E.worldAction(original,'travel','vieux-port');
assert.equal(port.scene,'belle_open','le voyage ne progresse pas la mission');
assert.equal(port.city.district,'vieux-port');
assert.equal(port.city.visited['vieux-port'],1);
assert.equal(original.city.district,'belle-rive','state immutable');
const purchase=E.worldAction(port,'buy','lockpick');
assert.equal(purchase.inventory.lockpick,1);
assert.equal(purchase.stats.money,180);
assert.throws(()=>E.worldAction(port,'buy','suit'),/quartier/);
const meeting=E.worldAction(port,'talk','enzo');
assert.equal(meeting.city.met.enzo,true);
assert.throws(()=>E.worldAction(meeting,'talk','enzo'),/déjà/);
const delivery=E.worldAction(meeting,'activity','courier');
assert.equal(delivery.stats.money,370);
assert.equal(delivery.city.activities.courier,true);
assert.throws(()=>E.worldAction(delivery,'activity','courier'),/déjà/);
const town=E.worldAction(delivery,'travel','centre-ville');
const suit=E.worldAction(town,'buy','suit');
assert.equal(suit.inventory.suit,1);
assert.throws(()=>E.worldAction(town,'talk','enzo'),/quartier/);
assert.equal(E.publicState(suit).city.district,'centre-ville');
const old=E.createGame();delete old.city;
assert.equal(E.publicState(old).city.district,'belle-rive','legacy saves upgraded');
const locked=E.choose(E.choose(E.choose(original,'belle_go'),'belle_accept'),'belle_bar');
assert.equal(locked.scene,'belle_barroom');
assert.equal(W.canExplore(locked),false);
assert.throws(()=>E.worldAction(locked,'travel','vieux-port'),/mission/);
assert.throws(()=>E.worldAction(locked,'buy','sneakers'),/quartier/);
console.log('V6 OK : 5 quartiers, déplacements, restrictions, achats locaux, rencontres uniques, activités, sauvegardes rétrocompatibles.');
